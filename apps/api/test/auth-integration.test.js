import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { decodeJwt } from 'jose';

test('JWT + PostgreSQL: registration, rotation/reuse, logout, live permissions and password change', { skip: process.env.RUN_DB_TESTS !== 'true' }, async (t) => {
  const { env } = await import('../src/config/env.js');
  if (env.NODE_ENV === 'production') throw new Error('Use banco de desenvolvimento.');
  const { db } = await import('../src/config/database.js');
  const { authService } = await import('../src/services/auth.service.js');
  const { createHttpServer } = await import('../src/http/server.js');
  const { routes } = await import('../src/routes/index.js');
  const ids = [], nonce = randomUUID();
  const server = createHttpServer({ routes, authenticate: authService.authenticate, logger: { info() {}, error() {} } });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const origin = `http://127.0.0.1:${server.address().port}/v1`;
  t.after(async () => {
    server.closeAllConnections(); await new Promise((resolve) => server.close(resolve));
    await db.user.deleteMany({ where: { id: { in: ids } } });
    await db.$disconnect();
  });
  async function call(path, { token, method = 'GET', body } = {}) {
    const response = await fetch(`${origin}${path}`, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: response.status === 204 ? null : await response.json() };
  }
  const email = `jwt-${nonce}@auth.test.local`, password = 'SenhaOriginal123!';
  const registration = await call('/auth/register', { method: 'POST', body: { name: 'Torcedor JWT', email, password } });
  assert.equal(registration.status, 201);
  const first = registration.body.data; ids.push(first.member.id);
  assert.equal(first.tokenType, 'Bearer'); assert.equal(decodeJwt(first.accessToken).sub, first.member.id);
  assert.ok(!JSON.stringify(first).includes('passwordHash'));
  assert.equal((await call('/me', { token: first.refreshToken })).status, 401);
  const stored = await db.refreshToken.findFirst({ where: { session: { userId: first.member.id } } });
  assert.notEqual(stored.tokenHash, first.refreshToken);
  assert.equal((await call('/auth/login', { method: 'POST', body: { email, password: 'wrong' } })).body.error.code, 'INVALID_CREDENTIALS');
  const login = async () => (await call('/auth/login', { method: 'POST', body: { email, password } })).body.data;
  const refresh = (refreshToken) => call('/auth/refresh', { method: 'POST', body: { refreshToken } });
  const renewed = await refresh(first.refreshToken);
  assert.equal(renewed.status, 200);
  assert.notEqual(renewed.body.data.refreshToken, first.refreshToken);
  const reuse = await refresh(first.refreshToken);
  assert.equal(reuse.status, 401); assert.equal(reuse.body.error.code, 'REFRESH_TOKEN_REUSED');
  assert.equal((await call('/me', { token: renewed.body.data.accessToken })).status, 401);
  assert.equal((await refresh(renewed.body.data.refreshToken)).status, 401);
  const second = await login();
  const list = (await call('/auth/sessions', { token: second.accessToken })).body.data;
  assert.equal(list.filter((session) => session.current).length, 1);
  assert.ok(!JSON.stringify(list).includes('tokenHash'));
  assert.equal((await call('/auth/logout', { token: second.accessToken, method: 'POST' })).status, 204);
  assert.equal((await call('/me', { token: second.accessToken })).status, 401);
  const third = await login(), fourth = await login();
  assert.equal((await call('/auth/logout-all', { token: third.accessToken, method: 'POST' })).status, 204);
  assert.equal((await call('/me', { token: fourth.accessToken })).status, 401);
  const fifth = await login();
  await db.user.update({ where: { id: first.member.id }, data: { role: 'ADMIN' } });
  assert.equal((await call('/admin/overview', { token: fifth.accessToken })).status, 200);
  await db.user.update({ where: { id: first.member.id }, data: { role: 'USER' } });
  assert.equal((await call('/admin/overview', { token: fifth.accessToken })).status, 403);
  const wrongPassword = await call('/auth/password', { token: fifth.accessToken, method: 'PUT', body: { currentPassword: 'incorrect', newPassword: 'SenhaNova12345!' } });
  assert.equal(wrongPassword.status, 401);
  assert.equal((await call('/me', { token: fifth.accessToken })).status, 200);
  const sixth = await login();
  assert.equal((await call('/auth/password', { token: fifth.accessToken, method: 'PUT', body: { currentPassword: password, newPassword: 'SenhaNova12345!' } })).status, 204);
  assert.equal((await call('/me', { token: sixth.accessToken })).status, 401);
  assert.equal((await call('/auth/login', { method: 'POST', body: { email, password } })).status, 401);
  const changed = await call('/auth/login', { method: 'POST', body: { email, password: 'SenhaNova12345!' } });
  assert.equal(changed.status, 200);
  await db.user.update({ where: { id: first.member.id }, data: { active: false } });
  assert.equal((await call('/me', { token: changed.body.data.accessToken })).status, 401);
  await db.user.update({ where: { id: first.member.id }, data: { active: true } });
  const parallel = (await call('/auth/login', { method: 'POST', body: { email, password: 'SenhaNova12345!' } })).body.data;
  const results = await Promise.all([refresh(parallel.refreshToken), refresh(parallel.refreshToken)]);
  assert.deepEqual(results.map((result) => result.status).sort(), [200, 401]);
  const winner = results.find((result) => result.status === 200).body.data;
  assert.equal((await call('/me', { token: winner.accessToken })).status, 401);
});
